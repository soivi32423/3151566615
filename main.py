# Обработка ответа на вопрос
@dp.callback_query(TestState.choosing_answer, F.data.startswith("ans_"))
async def process_answer(callback: CallbackQuery, state: FSMContext):
    points = int(callback.data.split("_")[1])
    
    data = await state.get_data()
    q_index = data["current_question"]
    score = data["score"]
    history = data["answers_history"]
    
    # Сохраняем баллы этого вопроса в историю (чтобы при нажатии "Назад" их можно было отнять)
    history.append(points)
    score += points
    
    q_index += 1
    chapter_key = data["chapter"]
    total_questions = len(TESTS_DATA[chapter_key]["questions"])
    
    if q_index < total_questions:
        # Переходим к следующему вопросу
        await state.update_data(current_question=q_index, score=score, answers_history=history)
        await send_question(callback.message, state)
    else:
        # Тест завершен, выводим результат
        await show_result(callback.message, state, score)
        
    await callback.answer()


# Кнопка «Назад» на предыдущий вопрос
@dp.callback_query(TestState.choosing_answer, F.data == "prev_question")
async def prev_question(callback: CallbackQuery, state: FSMContext):
    data = await state.get_data()
    q_index = data["current_question"]
    score = data["score"]
    history = data["answers_history"]
    
    if q_index > 0:
        q_index -= 1
        # Вычитаем баллы за последний отвеченный вопрос из истории
        last_points = history.pop()
        score -= last_points
        
        await state.update_data(current_question=q_index, score=score, answers_history=history)
        await send_question(callback.message, state)
        
    await callback.answer()


# Вывод результатов теста
async def show_result(message: Message, state: FSMContext, score: int):
    data = await state.get_data()
    chapter_key = data["chapter"]
    chapter = TESTS_DATA[chapter_key]
    
    # Подбираем уровень по баллам
    level_text = ""
    for max_score, text in chapter["results"]:
        if score <= max_score:
            level_text = text
            break
            
    result_message = (
        f"Тест завершён!\n\n"
        f"Набрано баллов: {score}\n"
        f"Твой уровень: {level_text}\n\n" 
    f"{OFFER_TEXT}"
    )
    
    keyboard = InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="В меню", callback_data="back_to_main")],
        [InlineKeyboardButton(text="Написать Марко", url="https://t.me/marko_bully")]
    ])
    
    try:
        await message.delete()
    except:
        pass
        
    await message.answer(result_message, reply_markup=keyboard)
    await state.clear()


